    - Responsive design

.PARAMETER JsonPath
    Path to the JSON file containing disk analysis results.
    This is typically generated by azure-managed-disk-telemetry-analysis.ps1.

.PARAMETER OutputPath
    Optional path for the output HTML file. If not specified, generates a timestamped
    filename in the same directory as the JSON input.

.EXAMPLE
    .\New-DiskAnalysisHtmlReport.ps1 -JsonPath "disk-analysis-20250115-123456.json"
    
    Generates HTML report from the specified JSON file.

.EXAMPLE
    .\New-DiskAnalysisHtmlReport.ps1 -JsonPath "disk-analysis.json" -OutputPath "custom-report.html"
    
    Generates HTML report with custom output filename.

.NOTES
    Requires JSON file generated by azure-managed-disk-telemetry-analysis.ps1.
    The script dynamically adapts to the JSON structure, making it resilient to future changes.
#>

