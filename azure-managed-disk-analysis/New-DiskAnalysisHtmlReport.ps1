.SYNOPSIS
    Generates an HTML report from Azure managed disk analysis JSON data.

.DESCRIPTION
    This script reads JSON output from azure-managed-disk-telemetry-analysis.ps1
    and generates a styled HTML report with interactive filtering, sorting, and
    color-coded recommendations.
    
    The HTML report features:
    - Summary statistics cards
    - Color-coded rows based on savings potential and efficiency
    - Interactive column sorting
